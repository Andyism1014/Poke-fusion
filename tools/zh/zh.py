def cmd_extract(args):
    files = load_all_po()
    changed = 0

    # ---- C strings ----
    occ = collections.defaultdict(list)  # key -> [(file, line)]
    for f, line, key in zhlib.scan_c_files():
        if skipped(f):
            continue
        occ[key].append((f, line))

    c_entries = {}   # (ctx, key) -> entry
    asm_entries = {}  # (ctx, label) -> entry
    for path, entries in files.items():
        kind = zhlib.po_kind(path)
        for e in entries:
            if kind == KIND_C:
                c_entries.setdefault((e.msgctxt, e.msgid), e)
            else:
                asm_entries.setdefault(e.msgctxt, e)

    used = set()
    new_by_po = collections.defaultdict(list)
    for key in sorted(occ, key=lambda k: (occ[k][0][0], occ[k][0][1])):
        places = occ[key]
        uncovered = []
        for f, line in places:
            e = c_entries.get((f, key))
            if e is not None:
                used.add(id(e))
                e.obsolete = False
            else:
                uncovered.append((f, line))
        if not uncovered:
            continue
        e = c_entries.get((None, key))
        refs = ["%s:%d" % fl for fl in uncovered]
        if e is None:
            e = PoEntry(key, "")
            c_entries[(None, key)] = e
            new_by_po[po_path_for_c(uncovered[0][0])].append(e)
        e.refs = refs[:8] + (["(+%d more)" % (len(refs) - 8)] if len(refs) > 8 else [])
        e.obsolete = False
        used.add(id(e))
    for (ctx, key), e in c_entries.items():
        if ctx is not None and id(e) in used:
            e.refs = ["%s:%d" % fl for fl in occ.get(key, []) if fl[0] == ctx][:8]

    # ---- script text ----
    seen_labels = set()
    for b in zhlib.scan_asm():
        if b.frlg or b.padded or skipped(b.file) or not b.text:
            continue
        if b.label in seen_labels:
            continue
        seen_labels.add(b.label)
        e = asm_entries.get(b.label) or asm_entries.get("%s:%s" % (b.file, b.label))
        if e is None:
            e = PoEntry(b.text, "", b.label)
            asm_entries[b.label] = e
            new_by_po[po_path_for_asm(b.file)].append(e)
        elif e.msgid != b.text:
            e.msgid = b.text
            if e.msgstr and "fuzzy" not in e.flags:
                e.flags.append("fuzzy")
        e.refs = ["%s:%d" % (b.file, b.line)]
        e.obsolete = False
        used.add(id(e))

    # ---- obsolete entries ----
    obsolete = 0
    for path, entries in files.items():
        for e in entries:
            if id(e) not in used and not e.obsolete:
                e.obsolete = True
                obsolete += 1

    for path, new in new_by_po.items():
        files.setdefault(path, []).extend(new)
    for path in files:
        # nothing to keep in an obsolete entry that was never translated
        files[path] = [e for e in files[path] if not (e.obsolete and not e.msgstr)]

    for path, entries in sorted(files.items()):
        # obsolete entries go last
        entries.sort(key=lambda e: e.obsolete)
        r = os.path.relpath(path, TEXT_DIR)
        source = r[:-3] if not r.startswith("scripts/") else "the script text in " + r[len("scripts/"):-3]
        if write_po(path, entries, source):
            changed += 1

    total_new = sum(len(v) for v in new_by_po.values())
    print("extract: %d new entries, %d newly obsolete, %d PO files written" % (total_new, obsolete, changed))


