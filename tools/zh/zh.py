def coverage():
    """Returns list of (po_path, kind, entry, translated) for every live entry."""
    rows = []
    for path in zhlib.po_files():
        kind = zhlib.po_kind(path)
        _, entries = zhlib.read_po(path)
        for e in entries:
            if e.obsolete:
                continue
            rows.append((path, kind, e, bool(e.msgstr)))
    return rows


def area_of(path):
    r = os.path.relpath(path, TEXT_DIR).replace(os.sep, "/")
    if r.startswith("scripts/maps/"):
        return "scripts: maps"
    if r.startswith("scripts/"):
        return "scripts: " + r.split("/")[1]
    if r.startswith("src/data/pokemon/species_info/"):
        return "C: species data"
    if r.startswith("src/data/"):
        return "C: " + "/".join(r.split("/")[:3]).replace(".po", "")
    return "C: src"


def cmd_stats(args):
    rows = coverage()
    by_area = collections.OrderedDict()
    by_file = collections.OrderedDict()
    for path, kind, e, tr in rows:
        a = area_of(path)
        t = by_area.setdefault(a, [0, 0, 0, 0, 0])
        f = by_file.setdefault(path, [0, 0, 0])
        t[0] += 1
        f[0] += 1
        n = len(e.msgid)
        t[2] += n
        if tr:
            t[1] += 1
            t[3] += n
            f[1] += 1
            if e.fuzzy:
                t[4] += 1
                f[2] += 1
    tot = [sum(v[i] for v in by_area.values()) for i in range(5)]
    print("%-34s %8s %8s %6s  %s" % ("area", "entries", "done", "%", "English chars (done/total)"))
    for a in sorted(by_area):
        v = by_area[a]
        print("%-34s %8d %8d %5.1f%%  %d/%d%s" % (a, v[0], v[1], 100.0 * v[1] / max(v[0], 1), v[3], v[2],
                                                  ("  (%d fuzzy)" % v[4]) if v[4] else ""))
    print("%-34s %8d %8d %5.1f%%  %d/%d" % ("TOTAL", tot[0], tot[1], 100.0 * tot[1] / max(tot[0], 1), tot[3], tot[2]))
    if args.files:
        print()
        for path, v in sorted(by_file.items()):
            if args.prefix and not rel(path).startswith(args.prefix):
                continue
            print("%5d/%-5d %s%s" % (v[1], v[0], rel(path), (" (%d fuzzy)" % v[2]) if v[2] else ""))


def cmd_missing(args):
    count = 0
    for path, kind, e, tr in coverage():
        if tr and not (args.fuzzy and e.fuzzy):
            continue
        if args.prefix and not rel(path).startswith(args.prefix):
            continue
        count += 1
        if args.count:
            continue
        if args.limit and count > args.limit:
            continue
        ctx = (" [%s]" % e.msgctxt) if e.msgctxt else ""
        print("%s%s: %s" % (rel(path), ctx, e.msgid))
    if args.count or (args.limit and count > args.limit):
        print("%d untranslated entries" % count)


