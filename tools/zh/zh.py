FIELD_MSGBOX_WIDTH = 216
_PLACEHOLDER = re.compile(r"\{[^}]*\}")
# Placeholders that stand for variable text (names, numbers); the others are symbols or codes.
_VARIABLE = re.compile(r"\{(PLAYER|RIVAL|STR_VAR_\d|B_\w+|KUN|DYNAMIC \w+)\}")


def lint_entry(kind, e, problems):
    tr = e.msgstr
    src = e.msgid
    # same placeholders and control codes
    ps = set(p for p in _PLACEHOLDER.findall(src) if _VARIABLE.match(p))
    pt = set(p for p in _PLACEHOLDER.findall(tr) if _VARIABLE.match(p))
    if ps != pt:
        problems.append("placeholders differ: English %s, Chinese %s" % (sorted(ps), sorted(pt)))
    if src.endswith("$") != tr.endswith("$"):
        problems.append("the English text %s with '$' but the translation doesn't" % ("ends" if src.endswith("$") else "doesn't end"))
    if re.search(r'(?<!\\)"', tr):
        problems.append("unescaped '\"' (write \\\" or use “ ”)")
    for ch in tr:
        if ch in "\t\r\n":
            problems.append("raw tab/newline")
            break
    if kind == KIND_ASM:
        # message box: 2 lines per page; first break \n, then \l
        for page in re.split(r"\\p", tr):
            breaks = re.findall(r"\\[nl]", page)
            if breaks and breaks[0] == "\\l":
                problems.append("page starts its second line with \\l (use \\n)")
            if breaks.count("\\n") > 1:
                problems.append("more than one \\n in a page (use \\l for the 3rd line onwards)")
        for text, w in zhlib.line_widths(tr):
            if w > FIELD_MSGBOX_WIDTH:
                problems.append("line is ~%dpx wide (message box: %dpx = 18 full-width chars): %s" % (w, FIELD_MSGBOX_WIDTH, text))


def cmd_lint(args):
    n = 0
    for path, kind, e, tr in coverage():
        if not tr:
            continue
        if args.prefix and not rel(path).startswith(args.prefix):
            continue
        problems = []
        lint_entry(kind, e, problems)
        for p in problems:
            n += 1
            print("%s: %s: %s" % (rel(path), e.msgctxt or e.msgid[:40], p))
    print("lint: %d problem(s)" % n)
    return 1 if n and args.strict else 0


