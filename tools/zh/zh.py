def load_font():
    """Glyphs from cjk_12px.hex (Fusion Pixel Font) plus the hand-drawn cjk_12px_extra.hex."""
    glyphs = {}
    for path in (zhlib.FONT_HEX, zhlib.FONT_HEX_EXTRA):
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                cp, w, rows = line.split(":")
                glyphs.setdefault(chr(int(cp, 16)), (int(w), [int(rows[i:i + 4], 16) for i in range(0, 48, 4)]))
    return glyphs


def latin_charmap_chars():
    """Characters with a mapping in the Latin (non-Japanese) part of charmap.txt."""
    chars = set()
    with open(os.path.join(ROOT, "charmap.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("@ Hiragana"):
                break
            m = re.match(r"^'(\\?.)'", line)
            if m:
                chars.add(m.group(1)[-1])
    return chars


def all_charmap_chars():
    chars = set()
    with open(os.path.join(ROOT, "charmap.txt"), encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^'(\\?.)'", line)
            if m:
                chars.add(m.group(1)[-1])
    return chars


# In translated text these use the CJK glyph even though charmap.txt has a Latin one.
FORCED_WIDE = "“”‘’…"

# Full-width punctuation that the automatic line breaking never puts at the start of a line.
NO_LINE_START = "，。！？、；：）」』》”’…—～"


def base_charset(font, latin):
    """The fixed part of the glyph table: GB2312 symbols + hanzi, in GB2312 order."""
    chars = []
    seen = set()
    for b1 in list(range(0xA1, 0xA4)) + list(range(0xB0, 0xF8)):
        for b2 in range(0xA1, 0xFF):
            try:
                ch = bytes([b1, b2]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if ch in font and ch not in seen and (ch not in latin or ch in FORCED_WIDE):
                chars.append(ch)
                seen.add(ch)
    return chars


def text_chars(s):
    """Characters of a raw game string, skipping {CONSTANTS} and escapes."""
    i = 0
    n = len(s)
    while i < n:
        c = s[i]
        if c == "{":
            j = s.find("}", i)
            i = n if j < 0 else j + 1
            continue
        if c == "\\":
            i += 2
            continue
        yield c
        i += 1


SMALL_FONT_SHIFT = 1  # rows the glyph moves up in FONT_SMALL / FONT_SMALL_NARROW (done in C)


def squeeze_rows(rows, ink_width):
    """Removes one column from a glyph whose ink is ink_width columns wide.

    Merges the two neighbouring columns that differ in the fewest rows (often
    a pair that only a horizontal stroke crosses), preferring the middle."""
    def bit(r, x):
        return r >> (15 - x) & 1

    best = None
    for c in range(0, ink_width - 1):
        cost = sum(1 for r in rows if bit(r, c) != bit(r, c + 1))
        key = (cost, abs(c - (ink_width - 2) / 2))
        if best is None or key < best[0]:
            best = (key, c)
    c = best[1]
    out = []
    for r in rows:
        left = r & ~((1 << (16 - c)) - 1) & 0xFFFF         # columns 0..c-1
        merged = (bit(r, c) | bit(r, c + 1)) << (15 - c)  # new column c
        right = (r << 1) & ((1 << (15 - c)) - 1)          # columns c+2.. shifted left
        out.append(left | merged | right)
    return out


def narrow_rows(width, rows, columns):
    """The glyph for the narrow (columns=1) or narrower (columns=2) fonts:
    squeezed so that it keeps its shadow and spacing column at 11 or 10px."""
    if width != 12:
        return rows
    for i in range(columns):
        rows = squeeze_rows(rows, 11 - i)
    return rows


def glyph_tiles(width, rows):
    """Converts a 12-row bitmap into the 2bpp 16x16 layout of the Latin fonts (64 bytes)."""
    cell = [[0] * 16 for _ in range(16)]
    for y in range(15):
        for x in range(min(width, 16)):
            cell[y][x] = 3  # accent = background inside the glyph cell, like the Latin fonts
    ink = [[False] * 16 for _ in range(16)]
    for r, bits in enumerate(rows):
        y = r + 1
        for x in range(16):
            if bits >> (15 - x) & 1:
                ink[y][x] = True
    for y in range(16):
        for x in range(16):
            if ink[y][x]:
                cell[y][x] = 1
    for y in range(16):
        for x in range(16):
            if not ink[y][x]:
                continue
            for dy, dx in ((0, 1), (1, 0), (1, 1)):
                yy, xx = y + dy, x + dx
                if yy < 16 and xx < 16 and not ink[yy][xx]:
                    cell[yy][xx] = 2
    out = bytearray()
    for ty in (0, 8):
        for tx in (0, 8):
            for y in range(ty, ty + 8):
                v = 0
                for i in range(8):
                    v |= cell[y][tx + i] << (14 - 2 * i)
                out += struct.pack("<H", v)
    return bytes(out)


def c_object_sources():
    """Same list as C_SRCS in the Makefile."""
    srcs = []
    for depth in ("*", "*/*", "*/*/*"):
        import glob
        for p in sorted(glob.glob(os.path.join(ROOT, "src", depth + ".c"))):
            if ".inc.c" in p:
                continue
            srcs.append(rel(p))
    return srcs


def cmd_build(args):
    out = args.out if os.path.isabs(args.out) else os.path.join(ROOT, args.out)
    errors = []

    def err(msg):
        errors.append(msg)

    translations = zhlib.load_translations(warn=zhlib.warn)
    font = load_font()
    latin = latin_charmap_chars()
    known = all_charmap_chars()

    # ---- glyph table ----
    base = base_charset(font, latin)
    extra_path = os.path.join(out, "extra_chars.txt")
    extras = []
    if os.path.exists(extra_path):
        with open(extra_path, encoding="utf-8") as f:
            extras = [c for c in f.read() if c != "\n" and c in font]
    index = {}
    for ch in base + extras:
        index.setdefault(ch, len(index))

    bad_chars = collections.defaultdict(set)
    for kind, table in translations.items():
        for (ctx, key), (msgstr, path, e) in sorted(table.items(), key=lambda kv: (kv[0][0] or "", kv[0][1])):
            if not msgstr:
                continue
            for ch in text_chars(msgstr):
                if ch in index:
                    continue
                if ch in latin and ch not in FORCED_WIDE:
                    continue
                if ch in font:
                    index[ch] = len(index)
                    extras.append(ch)
                elif ch not in known:
                    bad_chars[ch].add(rel(path))
    for ch, paths in sorted(bad_chars.items()):
        err("character %r (U+%04X) has no glyph (used in %s)" % (ch, ord(ch), ", ".join(sorted(paths))))
    if len(index) > zhlib.CJK_MAX_GLYPHS:
        err("too many glyphs (%d > %d)" % (len(index), zhlib.CJK_MAX_GLYPHS))
    if errors:
        for e in errors:
            sys.stderr.write("zh: error: %s\n" % e)
        sys.exit(1)

    os.makedirs(out, exist_ok=True)
    zhlib.write_if_changed(extra_path, "".join(extras) + "\n")

    codes = {}
    charmap_lines = ["@ Generated by tools/zh/zh.py build. Full-width glyphs for translated text."]
    glyph_data = bytearray()
    narrow_data = bytearray()
    narrower_data = bytearray()
    widths = bytearray()
    for ch, i in sorted(index.items(), key=lambda kv: kv[1]):
        lead, trail = zhlib.cjk_encode_index(i)
        codes[ch] = "%02X %02X" % (lead, trail)
        charmap_lines.append("'%s' = %s" % (ch, codes[ch]))
        w, rows = font[ch]
        glyph_data += glyph_tiles(w, rows)
        narrow_data += glyph_tiles(w, narrow_rows(w, rows, 1))
        narrower_data += glyph_tiles(w, narrow_rows(w, rows, 2))
        widths.append(w)
    zhlib.write_if_changed(os.path.join(out, "charmap.txt"), "\n".join(charmap_lines) + "\n")
    zhlib.write_if_changed(os.path.join(out, "cjk_glyphs.bin"), bytes(glyph_data), binary=True)
    zhlib.write_if_changed(os.path.join(out, "cjk_glyphs_narrow.bin"), bytes(narrow_data), binary=True)
    zhlib.write_if_changed(os.path.join(out, "cjk_glyphs_narrower.bin"), bytes(narrower_data), binary=True)
    zhlib.write_if_changed(os.path.join(out, "cjk_widths.bin"), bytes(widths), binary=True)
    outrel = rel(out)
    no_line_start = ", ".join("{0x%s, 0x%s}" % tuple(codes[ch].split()) for ch in NO_LINE_START if ch in codes)
    zhlib.write_if_changed(os.path.join(out, "cjk_font.h"),
                           "// Generated by tools/zh/zh.py build.\n"
                           "#define CJK_GLYPH_COUNT %d\n"
                           "#define CJK_NO_LINE_START_CHARS { %s }\n"
                           "static const u16 sCJKGlyphs[] = INCBIN_U16(\"%s/cjk_glyphs.bin\");\n"
                           "static const u16 sCJKGlyphsNarrow[] = INCBIN_U16(\"%s/cjk_glyphs_narrow.bin\");\n"
                           "static const u16 sCJKGlyphsNarrower[] = INCBIN_U16(\"%s/cjk_glyphs_narrower.bin\");\n"
                           "static const u8 sCJKGlyphWidths[] = INCBIN_U8(\"%s/cjk_widths.bin\");\n"
                           % (len(index), no_line_start, outrel, outrel, outrel, outrel))

    # ---- dictionary for preproc ----
    lines = []
    for (ctx, key), (msgstr, path, e) in sorted(translations[KIND_C].items(), key=lambda kv: (kv[0][0] or "", kv[0][1])):
        if msgstr:
            lines.append("c\t%s\t%s\t%s" % (ctx or "", key, msgstr))
    for (_, label), (msgstr, path, e) in sorted(translations[KIND_ASM].items(), key=lambda kv: kv[0][1]):
        if not msgstr:
            continue
        ctx = ""
        if ":" in label:
            ctx, label = label.rsplit(":", 1)
        lines.append("s\t%s\t%s\t%s" % (ctx, label, msgstr))
    for l in lines:
        if l.count("\t") != 3 or "\n" in l:
            err("bad entry: %r" % l[:80])
    zhlib.write_if_changed(os.path.join(out, "translations.tsv"), "\n".join(lines) + ("\n" if lines else ""))

    # ---- per-object dependency hashes ----
    def entry_digest(h, key, msgstr):
        h.update(key.encode("utf-8"))
        h.update(b"\0")
        h.update(msgstr.encode("utf-8"))
        h.update(b"\0")
        h.update(" ".join(codes.get(ch, "") for ch in text_chars(msgstr)).encode("ascii"))
        h.update(b"\n")

    c_trans = translations[KIND_C]
    keys_by_file = collections.defaultdict(set)
    for f, line, key in zhlib.scan_c_files():
        keys_by_file[f].add(key)
    srcs = c_object_sources()
    closures = zhlib.c_include_closure(srcs)
    for src in srcs:
        h = hashlib.sha1()
        items = []
        for f in sorted(closures[src]):
            for key in sorted(keys_by_file.get(f, ())):
                for ctx in (f, None):
                    t = c_trans.get((ctx, key))
                    if t and t[0]:
                        items.append((f if ctx else "", key, t[0]))
        for ctx, key, msgstr in sorted(set(items)):
            entry_digest(h, ctx + "\t" + key, msgstr)
        zhlib.write_if_changed(os.path.join(out, "deps", src + ".hash"), h.hexdigest() + "\n")

    a_trans = translations[KIND_ASM]
    blocks_by_file = collections.defaultdict(set)
    for b in zhlib.scan_asm():
        blocks_by_file[b.file].add(b.label)
    for root in zhlib.asm_root_files():
        r = rel(root)
        h = hashlib.sha1()
        for f in sorted(zhlib.asm_include_closure(r)):
            for label in sorted(blocks_by_file.get(f, ())):
                for k in (label, "%s:%s" % (f, label)):
                    t = a_trans.get((None, k))
                    if t and t[0]:
                        entry_digest(h, k, t[0])
        zhlib.write_if_changed(os.path.join(out, "deps", r + ".hash"), h.hexdigest() + "\n")

    if errors:
        for e in errors:
            sys.stderr.write("zh: error: %s\n" % e)
        sys.exit(1)
    nc = sum(1 for v in c_trans.values() if v[0])
    na = sum(1 for v in a_trans.values() if v[0])
    print("zh: %d C strings, %d script texts, %d glyphs (%d beyond GB2312)" % (nc, na, len(index), len(extras)))


