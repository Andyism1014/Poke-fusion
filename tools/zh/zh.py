def cmd_fit(args):
    """Checks translated names and descriptions against the UI widths."""
    from import_pokeapi import parse_blocks
    translations = zhlib.load_translations()[KIND_C]
    problems = 0
    for what, src, field, font, limit, where in FIT_CHECKS:
        files = [src] if src.endswith((".h", ".c")) else sorted(
            src + f for f in os.listdir(os.path.join(ROOT, src)) if f.endswith(".h"))
        seen = set()
        for f in files:
            for const, fields, _ in parse_blocks(f):
                english = fields.get(field)
                if english is None or (f, english) in seen:
                    continue
                seen.add((f, english))
                t = translations.get((f, english)) or translations.get((None, english))
                if not t or not t[0]:
                    continue
                w = zhlib.text_width(t[0], font)
                if w > limit:
                    problems += 1
                    print("%-20s %s: %s is %dpx in %s (%s allows %dpx)" % (what, const, t[0], w, font, where, limit))
    print("fit: %d problem(s)" % problems)


