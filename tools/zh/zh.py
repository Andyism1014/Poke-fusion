PO_HEADER = """Simplified Chinese translation of %s.
Generated by `python3 tools/zh/zh.py extract`; fill in the msgstr lines.
See docs/fusion/CHINESE.md for the rules (line width, \\n \\l \\p, placeholders).
"""

# Files whose text is never extracted: FireRed/LeafGreen-only data and debug menus.
SKIP_PATTERNS = (
    re.compile(r"frlg", re.I),
    re.compile(r"(^|/)(debug|battle_debug|pokemon_sprite_visualizer)\.(c|h|inc)$"),
    re.compile(r"^include/test/"),
    re.compile(r"^src/data/.*_frlg"),
)


def skipped(path):
    return any(p.search(path) for p in SKIP_PATTERNS)


def po_path_for_c(src):
    return os.path.join(TEXT_DIR, src + ".po")


def po_path_for_asm(src):
    p = src
    if p.startswith("data/"):
        p = p[len("data/"):]
    if p.startswith("maps/") and p.endswith("/scripts.inc"):
        p = "maps/" + p[len("maps/"):-len("/scripts.inc")]
    else:
        p = os.path.splitext(p)[0]
    return os.path.join(TEXT_DIR, "scripts", p + ".po")


def load_all_po():
    files = {}
    for path in zhlib.po_files():
        header, entries = zhlib.read_po(path)
        files[path] = entries
    return files


def write_po(path, entries, source):
    data = zhlib.format_po(PO_HEADER % source, entries)
    return zhlib.write_if_changed(path, data + ("\n" if not data.endswith("\n") else ""))


