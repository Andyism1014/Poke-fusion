#!/usr/bin/env python3
"""Simplified Chinese translation tool. See docs/fusion/CHINESE.md.

    python3 tools/zh/zh.py extract           add new/changed English text to text_zh/**.po
    python3 tools/zh/zh.py stats [--files]   translation coverage
    python3 tools/zh/zh.py missing [PREFIX]  list untranslated entries (PREFIX filters PO paths)
    python3 tools/zh/zh.py lint [PREFIX]     check widths, line breaks and control codes
    python3 tools/zh/zh.py fit               check translated names against the UI widths
    python3 tools/zh/zh.py apply FILE.tsv    fill msgstr from a TSV file (KEY<TAB>CHINESE)
    python3 tools/zh/zh.py build --out DIR   generate the build inputs (run by `make chinese`)
"""

