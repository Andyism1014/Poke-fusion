def cmd_apply(args):
    """Fills translations from a TSV file.

    Each line is KEY<TAB>CHINESE, or CONTEXT<TAB>KEY<TAB>CHINESE. KEY is the
    English text of a C string, or the label of a script text block. Lines
    starting with # are ignored. Existing translations are kept unless --force."""
    rows = []
    with open(args.tsv, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) == 2:
                rows.append((None, parts[0], parts[1]))
            elif len(parts) == 3:
                rows.append((parts[0] or None, parts[1], parts[2]))
            else:
                sys.exit("%s:%d: expected 2 or 3 tab-separated columns" % (args.tsv, n))
    wanted = {}
    for ctx, key, zh in rows:
        wanted[(ctx, key)] = zh
    used = set()
    changed_files = 0
    filled = 0
    for path in zhlib.po_files():
        if args.prefix and not rel(path).startswith(args.prefix):
            continue
        kind = zhlib.po_kind(path)
        header, entries = zhlib.read_po(path)
        changed = False
        for e in entries:
            if e.obsolete:
                continue
            if kind == KIND_ASM:
                k = (None, e.msgctxt)
            else:
                k = (e.msgctxt, e.msgid)
            zh = wanted.get(k)
            if zh is None:
                continue
            used.add(k)
            if e.msgstr and not args.force:
                continue
            if e.msgstr != zh:
                e.msgstr = zh
                if "fuzzy" in e.flags:
                    e.flags.remove("fuzzy")
                changed = True
                filled += 1
        if changed:
            r = os.path.relpath(path, TEXT_DIR)
            source = r[:-3] if not r.startswith("scripts/") else "the script text in " + r[len("scripts/"):-3]
            write_po(path, entries, source)
            changed_files += 1
    unknown = [k for k in wanted if k not in used]
    for ctx, key in unknown[:20]:
        zhlib.warn("no entry for %s%r" % (("[%s] " % ctx) if ctx else "", key))
    if len(unknown) > 20:
        zhlib.warn("... and %d more without an entry" % (len(unknown) - 20))
    print("apply: %d translations filled in %d PO files, %d keys without an entry" % (filled, changed_files, len(unknown)))


