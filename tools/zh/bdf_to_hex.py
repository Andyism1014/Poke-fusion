#!/usr/bin/env python3
"""Converts the Fusion Pixel Font 12px BDF into graphics/fonts/zh/cjk_12px.hex.

Only needed when updating the font. Usage:

    python3 tools/zh/bdf_to_hex.py fusion-pixel-12px-proportional-zh_hans.bdf

The release zip is at
https://github.com/TakWolf/fusion-pixel-font/releases (12px proportional, BDF).

Output format, one glyph per line, sorted by code point:

    CODEPOINT:WIDTH:ROWS

CODEPOINT is hex, WIDTH is the advance in pixels, ROWS is 12 rows of 4 hex
digits each (16 bits per row, leftmost pixel = most significant bit). Row 0 is
10px above the baseline, row 11 is 1px below it -- the 12px em box of the font.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import zhlib  # noqa: E402

EM_TOP = 10      # y (relative to the baseline) of row 0
EM_ROWS = 12


def wanted(cp):
    ch = chr(cp)
    if zhlib.is_wide_char(ch):
        return True
    try:
        b = ch.encode("gb2312")
    except UnicodeEncodeError:
        return False
    # GB2312 rows 1-3 (symbols, full-width forms) and the hanzi rows.
    return len(b) == 2 and (0xA1 <= b[0] <= 0xA3 or b[0] >= 0xB0)


def parse_bdf(path):
    glyphs = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().split("\n")
    i = 0
    n = len(lines)
    while i < n:
        if not lines[i].startswith("STARTCHAR"):
            i += 1
            continue
        cp = None
        dwidth = None
        bbx = None
        rows = []
        i += 1
        while i < n and not lines[i].startswith("ENDCHAR"):
            l = lines[i]
            if l.startswith("ENCODING "):
                cp = int(l.split()[1])
            elif l.startswith("DWIDTH "):
                dwidth = int(l.split()[1])
            elif l.startswith("BBX "):
                bbx = [int(x) for x in l.split()[1:5]]
            elif l.startswith("BITMAP"):
                i += 1
                while i < n and not lines[i].startswith("ENDCHAR"):
                    rows.append(lines[i].strip())
                    i += 1
                break
            i += 1
        if cp is not None and cp >= 0 and bbx is not None:
            glyphs[cp] = (dwidth, bbx, rows)
        i += 1
    return glyphs


def to_em_rows(dwidth, bbx, rows):
    w, h, xoff, yoff = bbx
    em = [0] * EM_ROWS
    for r, hexrow in enumerate(rows):
        bits = int(hexrow, 16) if hexrow else 0
        nbits = len(hexrow) * 4
        y = yoff + h - 1 - r          # y of this bitmap row relative to the baseline
        er = EM_TOP - y
        if not 0 <= er < EM_ROWS:
            if bits:
                return None  # ink outside the em box: skip the glyph
            continue
        for x in range(w):
            if bits >> (nbits - 1 - x) & 1:
                px = x + xoff
                if 0 <= px < 16:
                    em[er] |= 1 << (15 - px)
    return em


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    glyphs = parse_bdf(sys.argv[1])
    out = []
    skipped = 0
    for cp in sorted(glyphs):
        if not wanted(cp):
            continue
        dwidth, bbx, rows = glyphs[cp]
        em = to_em_rows(dwidth, bbx, rows)
        if em is None or dwidth is None or not 1 <= dwidth <= 16:
            skipped += 1
            continue
        out.append("%04X:%d:%s" % (cp, dwidth, "".join("%04X" % r for r in em)))
    os.makedirs(os.path.dirname(zhlib.FONT_HEX), exist_ok=True)
    header = [
        "# Glyph data derived from Fusion Pixel Font 12px proportional (%s)." % os.path.basename(sys.argv[1]),
        "# Copyright (c) 2022, TakWolf (https://takwolf.com), with Reserved Font Name 'Fusion Pixel'.",
        "# Licensed under the SIL Open Font License 1.1: see OFL.txt and LICENSE/ in this folder.",
        "# Generated by tools/zh/bdf_to_hex.py. Format: CODEPOINT:WIDTH:12 rows of 16 bits.",
    ]
    with open(zhlib.FONT_HEX, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + out) + "\n")
    print("wrote %d glyphs to %s (%d skipped)" % (len(out), zhlib.rel(zhlib.FONT_HEX), skipped))


if __name__ == "__main__":
    main()
